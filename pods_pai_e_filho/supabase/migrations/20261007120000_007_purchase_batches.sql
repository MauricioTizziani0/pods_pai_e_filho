-- Compras originam lotes. Estoque e vendas sem origem conhecida continuam sem lote.
create table public.purchase_batches (
  id uuid primary key default gen_random_uuid(),
  batch_number bigint generated by default as identity unique,
  purchase_date date not null default current_date,
  notes text,
  is_legacy boolean not null default false,
  status text not null default 'ABERTO' check (status in ('ABERTO', 'FINALIZADO', 'CANCELADO')),
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  closed_at timestamptz,
  cancelled_at timestamptz
);

create table public.batch_items (
  id uuid primary key default gen_random_uuid(),
  batch_id uuid not null references public.purchase_batches (id) on delete restrict,
  product_id uuid not null references public.products (id) on delete restrict,
  variant_id uuid not null references public.product_variants (id) on delete restrict,
  product_name text not null,
  variant_name text not null,
  quantity_purchased integer not null check (quantity_purchased > 0),
  unit_cost numeric(14, 2) not null check (unit_cost >= 0),
  created_at timestamptz not null default now()
);
create index batch_items_batch_idx on public.batch_items (batch_id);
create index batch_items_variant_idx on public.batch_items (variant_id, created_at);

alter table public.stock_movements
  add column batch_id uuid references public.purchase_batches (id) on delete restrict,
  add column batch_item_id uuid references public.batch_items (id) on delete restrict;

