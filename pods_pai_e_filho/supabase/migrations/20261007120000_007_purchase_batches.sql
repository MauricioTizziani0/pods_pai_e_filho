-- Keep old cost snapshots and allow exact line totals when a sale spans lots.
alter table public.sale_items
  alter column line_cost drop expression,
  alter column line_father_profit drop expression;
update public.sale_items
set line_cost = case when cost_price_unit is null then null
                     else (quantity::numeric * cost_price_unit)::numeric(14, 2) end,
    line_father_profit = case when cost_price_unit is null then null
                              else (quantity::numeric * (unit_transfer - cost_price_unit))::numeric(14, 2) end;
alter table public.sale_items drop constraint if exists sale_items_transfer_covers_cost;

create or replace function public.snapshot_sale_item_cost()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_cost numeric(14, 2);
  v_override text := current_setting('pods.batch_cost_override', true);
begin
  if nullif(v_override, '') is not null then
    new.cost_price_unit := v_override::numeric(14, 2);
  elsif tg_op = 'INSERT' or new.product_id is distinct from old.product_id then
    select cost_price into v_cost from public.products where id = new.product_id and active;
    if v_cost is null then raise exception 'Custo do estoque sem lote não está configurado para este produto'; end if;
    new.cost_price_unit := v_cost;
  else
    new.cost_price_unit := old.cost_price_unit;
  end if;
  if new.cost_price_unit < 0 then raise exception 'Preço de custo deve ser maior ou igual a zero'; end if;
  if new.unit_price < new.unit_transfer then raise exception 'O preço de venda não pode ser menor que o repasse ao pai'; end if;
  return new;
end;
$$;

create or replace function public.set_sale_item_cost_totals()
returns trigger language plpgsql set search_path = public as $$
begin
  if new.line_cost is null and new.cost_price_unit is not null then
    new.line_cost := (new.quantity::numeric * new.cost_price_unit)::numeric(14, 2);
  end if;
  if new.line_cost is not null then
    new.line_father_profit := (new.quantity::numeric * new.unit_transfer - new.line_cost)::numeric(14, 2);
  else
    new.line_father_profit := null;
  end if;
  return new;
end;
$$;
drop trigger if exists sale_items_cost_totals on public.sale_items;
create trigger sale_items_cost_totals
  before insert or update of quantity, unit_transfer, cost_price_unit, line_cost
  on public.sale_items for each row execute function public.set_sale_item_cost_totals();

create or replace function public.validate_stock_movement_batch_item()
returns trigger language plpgsql set search_path = public as $$
declare v_batch uuid;
begin
  if new.batch_item_id is null then
    if new.batch_id is not null then raise exception 'Movimentação precisa apontar para o item do lote'; end if;
    return new;
  end if;
  select batch_id into v_batch from public.batch_items where id = new.batch_item_id;
  if v_batch is null or new.batch_id is distinct from v_batch then
    raise exception 'Item e lote da movimentação não correspondem';
  end if;
  return new;
end;
$$;

create or replace view public.stock_movement_history
with (security_invoker = true) as
select m.id, m.product_id, m.variant_id, m.movement_type, mt.name as movement_name,
